async def test_body_limit_with_and_without_content_length(config, session_factory):
    config.max_request_body_bytes = 40
    app = create_app(config, session_factory)
    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://localhost") as client:
        assert_error(await client.post("/v1/items", content=b"x" * 41), 413, "body_too_large")

        async def chunks():
            yield b"x" * 20
            yield b"y" * 21

        streamed = await client.post(
            "/v1/items", content=chunks(), headers={"Origin": "http://localhost:3000"}
        )
        assert_error(streamed, 413, "body_too_large")
        assert streamed.request.headers.get("content-length") is None
        assert streamed.headers["access-control-allow-origin"] == "http://localhost:3000"
        assert_error(await client.post("/v1/items", content=b"x" * 40), 401, "unauthorized")


async def test_rollback_after_flushed_write(app, client, session_factory, test_user, capsys):
    @app.post("/test-write")
    async def write(db: RequestSession, error: str) -> dict[str, str]:
        await ItemRepository(db).create(test_user.id, "will be rolled back")
        if error == "expected":
            raise HTTPException(400, "Test request error")
        raise RuntimeError("private-value")

    for kind, status, code in (
        ("expected", 400, "bad_request"),
        ("unexpected", 500, "internal_error"),
    ):
        response = await client.post(
            f"/test-write?error={kind}",
            headers={"X-Request-Id": "rollback-42", "Origin": "http://localhost:3000"},
        )
        assert_error(response, status, code)
        assert response.headers["x-request-id"] == "rollback-42"
        assert response.headers["access-control-allow-origin"] == "http://localhost:3000"
        assert "private-value" not in response.text
        async with session_factory() as session:
            assert await session.scalar(select(Item)) is None

    output = capsys.readouterr().out
    assert "RuntimeError" in output
    assert "private-value" not in output


