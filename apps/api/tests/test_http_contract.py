async def test_security_headers_host_and_cors(config, session_factory):
    config.trusted_hosts = ["api.example"]
    config.cors_origins = ["https://web.example"]
    app = create_app(config, session_factory)
    async with AsyncClient(
        transport=ASGITransport(app=app), base_url="https://api.example"
    ) as client:
        response = await client.get(
            "/health", headers={"Origin": "https://web.example", "X-Request-Id": "not a trace ID"}
        )
        assert response.status_code == 200
        generated_id = UUID(response.headers["x-request-id"])
        assert generated_id.version == 4
        assert response.headers["x-content-type-options"] == "nosniff"
        assert response.headers["x-frame-options"] == "DENY"
        assert response.headers["content-security-policy"] == "frame-ancestors 'none'"
        assert response.headers["referrer-policy"] == "no-referrer"
        assert response.headers["strict-transport-security"] == "max-age=31536000"
        assert response.headers["access-control-allow-origin"] == "https://web.example"
        assert response.headers["access-control-expose-headers"] == "X-Request-Id"

        for probe in ("/health", "/ready"):
            assert (await client.get(probe, headers={"Host": "127.0.0.1"})).status_code == 200
        wrong_host = await client.get("/v1", headers={"Host": "untrusted.example"})
        assert_error(wrong_host, 400, "invalid_host")
        assert wrong_host.headers["x-frame-options"] == "DENY"

        preflight = {
            "Access-Control-Request-Method": "POST",
            "Access-Control-Request-Headers": "Idempotency-Key, X-Request-Id",
        }
        good = await client.options(
            "/v1/items", headers={**preflight, "Origin": "https://web.example"}
        )
        assert good.status_code == 200
        bad = await client.options(
            "/v1/items", headers={**preflight, "Origin": "https://wrong.example"}
        )
        assert_error(bad, 400, "cors_disallowed")
        assert "access-control-allow-origin" not in bad.headers


