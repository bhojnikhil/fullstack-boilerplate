async def test_adopt_legacy_schema_without_losing_data(config, empty_db_engine):
    user_id, item_id = uuid4(), uuid4()
    ddl = Path(__file__).with_name("fixtures").joinpath("pre_alembic_schema.sql").read_text()
    async with empty_db_engine.begin() as connection:
        await connection.exec_driver_sql(ddl)
        assert await connection.scalar(text("SELECT to_regclass('alembic_version')")) is None
        await connection.execute(
            text(
                "INSERT INTO users (id, email, name, is_active) VALUES (:id, :email, 'Legacy', true)"
            ),
            {"id": user_id, "email": "legacy@example.com"},
        )
        await connection.execute(
            text(
                "INSERT INTO items (id, user_id, title, is_active) VALUES (:id, :user, :title, true)"
            ),
            {"id": item_id, "user": user_id, "title": "Pre-Alembic item"},
        )

    async with empty_db_engine.connect() as connection:
        await connection.run_sync(lambda conn: command.stamp(migration_config(conn), "0001"))
        await connection.run_sync(lambda conn: command.upgrade(migration_config(conn), "head"))
        await connection.run_sync(lambda conn: command.check(migration_config(conn)))

    app = create_app(config, async_sessionmaker(empty_db_engine, expire_on_commit=False))
    headers = {"Authorization": f"Bearer {create_access_token({'sub': str(user_id)}, config)}"}
    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://localhost") as client:
        assert (await client.get("/ready")).status_code == 200
        restored = await client.get(f"/v1/items/{item_id}", headers=headers)
    assert restored.status_code == 200
    assert restored.json()["id"] == str(item_id)
    assert restored.json()["title"] == "Pre-Alembic item"


@pytest.mark.parametrize(
    ("migration", "revisions", "ddl"),
    [
        (command.upgrade, "0001:0002", "CREATE INDEX CONCURRENTLY ix_items_user_created_id"),
        (
            command.downgrade,
            "0002:0001",
            "DROP INDEX CONCURRENTLY IF EXISTS ix_items_user_created_id",
        ),
    ],
)
def test_pagination_index_ddl_runs_outside_transaction(migration, revisions, ddl):
    output = StringIO()
    migration(Config("alembic.ini", output_buffer=output), revisions, sql=True)
    statements = output.getvalue()
    before, after = statements.split(ddl, 1)
    assert before.rfind("COMMIT;") > before.rfind("BEGIN;")
    assert "BEGIN;" in after


async def test_concurrent_index_migration_can_retry_after_partial_upgrade(empty_db_engine):
    async with empty_db_engine.connect() as connection:
        await connection.run_sync(lambda conn: command.upgrade(migration_config(conn), "0001"))
        # Simulate interruption after the concurrent build committed but before revision 0002 did.
        await connection.execute(
            text("CREATE INDEX ix_items_user_created_id ON items (user_id, created_at, id)")
        )
        await connection.commit()
        await connection.run_sync(lambda conn: command.upgrade(migration_config(conn), "head"))
        await connection.run_sync(lambda conn: command.check(migration_config(conn)))
        assert (
            await connection.scalar(
                text(
                    "SELECT indisvalid FROM pg_index WHERE indexrelid = 'ix_items_user_created_id'::regclass"
                )
            )
            is True
        )


