def test_openapi_operation_ids_and_error_schema(app):
    operations = app.openapi()["paths"]
    ids = [
        operation["operationId"]
        for methods in operations.values()
        for operation in methods.values()
    ]
    assert len(ids) == len(set(ids))
    assert set(operations) - {"/ready", "/health"} == {
        path for path in operations if path.startswith("/v1")
    }
    listing = operations["/v1/items"]["get"]
    assert listing["operationId"] == "items_list_items"
    assert (
        listing["responses"]["200"]["content"]["application/json"]["schema"]["$ref"]
        == "#/components/schemas/ItemPage"
    )
    assert (
        listing["responses"]["422"]["content"]["application/json"]["schema"]["$ref"]
        == "#/components/schemas/ErrorEnvelope"
    )
