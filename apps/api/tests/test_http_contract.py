async def test_adopt_legacy_schema_without_losing_data(client, auth_headers, test_db_engine):
    original = await client.post(
        "/v1/items", headers=auth_headers, json={"title": "Pre-Alembic item"}
    )
    assert original.status_code == 201
    async with test_db_engine.begin() as connection:
        await connection.run_sync(lambda conn: command.downgrade(migration_config(conn), "0001"))
        await connection.execute(text("DROP TABLE alembic_version"))
        await connection.run_sync(lambda conn: command.stamp(migration_config(conn), "0001"))
        await connection.run_sync(lambda conn: command.upgrade(migration_config(conn), "head"))
        await connection.run_sync(lambda conn: command.check(migration_config(conn)))

    assert (await client.get("/ready")).status_code == 200
    restored = await client.get(f"/v1/items/{original.json()['id']}", headers=auth_headers)
    assert restored.json() == original.json()


